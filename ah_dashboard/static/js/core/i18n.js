/** @type {'en'|'nl'} */
let lang = (() => {
  const saved = storage.get(KEYS.lang);
  if (saved === 'en' || saved === 'nl') return saved;
  return ((typeof navigator !== 'undefined' && navigator.language) || '').toLowerCase().startsWith('nl') ? 'nl' : 'en';
})();

export function getLang() { return lang; }

/** @param {string} value */
export function setLang(value) {
  lang = value === 'nl' ? 'nl' : 'en';
  storage.set(KEYS.lang, lang);
}

/** Translate `key`; function entries receive `args` (plurals, names). */
/**
 * @param {string} key
 * @param {...any} args
 * @returns {any} text (or a list, e.g. month names)
 */
export function t(key, ...args) {
  // Own keys only: "constructor", "__proto__" etc. must not resolve to
  // Object.prototype members.
  let v = Object.hasOwn(I18N[lang], key) ? I18N[lang][key] : undefined;
  if (v === undefined && Object.hasOwn(I18N.en, key)) v = I18N.en[key];
  if (v === undefined) return String(key);
  return typeof v === 'function' ? v(...args) : v;
}

/** @param {string} key */
export function hasKey(key) { return Object.hasOwn(I18N.en, key); }

/** Fill every element marked with data-i18n / -ph / -title / -aria. */
/** @param {Document|HTMLElement} [root] */
export function applyStaticI18n(root = document) {
  document.documentElement.lang = lang;
  document.title = t('title');
  root.querySelectorAll('[data-i18n]').forEach((/** @type {HTMLElement} */ el) => {
    el.textContent = el.dataset.n !== undefined ? t(el.dataset.i18n, el.dataset.n) : t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((/** @type {HTMLInputElement} */ el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((/** @type {HTMLElement} */ el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((/** @type {HTMLElement} */ el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
